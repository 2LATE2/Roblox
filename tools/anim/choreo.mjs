const DEG = Math.PI / 180;
function rotY(x, z, deg) {
  const c = Math.cos(deg * DEG);
  const s = Math.sin(deg * DEG);
  return [x * c + z * s, -x * s + z * c];
}

function legAt(side, t) {
  const heel = HEEL[side].at(t);
  const kneeOut = KNEE_OUT.at(t);
  if (t <= T_OFF) {
    const p = PRE[side];
    return { x: p.x.at(t), z: p.z.at(t), lift: p.lift.at(t), yaw: p.yaw.at(t), heel, kneeOut };
  }
  const u = t >= T_LAND ? 1 : smoothstep(T_OFF, T_LAND, t);
  const yawOff = P.yaw.at(T_OFF);
  const rot = t >= T_LAND ? P.yaw.at(T_LAND) : P.yaw.at(t) - yawOff * (1 - u);
  const startX = PRE[side].x.at(T_OFF);
  const relX = lerp(startX, LAND[side].x, u);
  const tuck = t < T_LAND ? 0.28 * Math.sin(Math.PI * u) : 0;
  const relZ = lerp(0, LAND[side].z, u) + tuck;
  const [x, z] = rotY(relX, relZ, rot);
  return { x, z, lift: LIFT_AIR.at(t), yaw: rot + LAND[side].yaw * u, heel, kneeOut };
}

// ---------------------------------------------------------------- sample
export function controlsAt(t) {
  const arm = (side) => {
    const a = ARMS[side];
    return {
      yaw: a.swing.yaw(t),
      pitch: a.swing.pitch(t),
      bend: Math.max(0, a.swing.bend(t)),
      pole: a.pole.map((f) => f(t)),
      wrist: a.wrist.map((f) => f(t)),
      twist: a.twist.at(t),
      contact: { weight: a.contact.at(t), point: gripPoint(side, t) },
    };
  };
  return {
    pelvis: { x: P.x.at(t), y: P.y.at(t), z: P.z.at(t), pitch: P.pitch.at(t), yaw: P.yaw.at(t), roll: P.roll.at(t) },
    spine: { pitch: SPINE.pitch(t), yaw: SPINE.yaw(t), roll: SPINE.roll(t) },
    neck: { pitch: NECK.pitch(t), yaw: NECK.yaw(t), roll: NECK.roll(t) },
    arms: { Left: arm('Left'), Right: arm('Right') },
    legs: { Left: legAt('Left', t), Right: legAt('Right', t) },
  };
}
