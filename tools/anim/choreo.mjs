function armTrack(keys) {
  const col = (i) => K(...keys.map((k) => [k[0], k[i]]));
  return { yaw: sp(col(1), ARM_SPRING), pitch: sp(col(2), ARM_SPRING), bend: sp(col(3), ARM_SPRING) };
}
function vecTrack(keys, cfg) {
  const col = (i) => K(...keys.map((k) => [k[0], k[i]]));
  if (!cfg) return [col(1), col(2), col(3)].map((c) => (t) => c.at(t));
  return [sp(col(1), cfg), sp(col(2), cfg), sp(col(3), cfg)];
}

