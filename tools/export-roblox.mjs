// Roblox exporters: KeyframeSequence (.rbxmx), generated Luau data module and
// the drop-in demo kit (chest + client script + KeyframeSequence in one model).
import fs from 'node:fs';
import path from 'node:path';
import * as THREE from 'three';
import { JOINTS } from './anim/rig.mjs';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const num = (v) => {
  const r = Math.round(v * 1e6) / 1e6;
  return Object.is(r, -0) || r === 0 ? '0' : String(r);
};

let refCounter = 0;
const nextRef = () => 'RBX' + (++refCounter).toString(16).toUpperCase().padStart(8, '0');
const item = (cls, props, children = []) =>
  `<Item class="${cls}" referent="${nextRef()}"><Properties>${props.join('')}</Properties>${children.join('')}</Item>`;
const P = {
  string: (n, v) => `<string name="${n}">${esc(v)}</string>`,
  float: (n, v) => `<float name="${n}">${num(v)}</float>`,
  bool: (n, v) => `<bool name="${n}">${v ? 'true' : 'false'}</bool>`,
  token: (n, v) => `<token name="${n}">${v}</token>`,
  vector3: (n, [x, y, z]) => `<Vector3 name="${n}"><X>${num(x)}</X><Y>${num(y)}</Y><Z>${num(z)}</Z></Vector3>`,
  color3uint8: (n, [r, g, b]) => `<Color3uint8 name="${n}">${(0xff000000 | (r << 16) | (g << 8) | b) >>> 0}</Color3uint8>`,
  cframe(n, p, q) {
    const e = new THREE.Matrix4().makeRotationFromQuaternion(q).elements; // column-major
    const R = [e[0], e[4], e[8], e[1], e[5], e[9], e[2], e[6], e[10]];
    const names = ['R00', 'R01', 'R02', 'R10', 'R11', 'R12', 'R20', 'R21', 'R22'];
    return `<CoordinateFrame name="${n}"><X>${num(p.x)}</X><Y>${num(p.y)}</Y><Z>${num(p.z)}</Z>${R.map((v, i) => `<${names[i]}>${num(v)}</${names[i]}>`).join('')}</CoordinateFrame>`;
  },
  source: (n, src) => {
    if (src.includes(']]>')) throw new Error('Luau source contains ]]>');
    return `<ProtectedString name="${n}"><![CDATA[${src}]]></ProtectedString>`;
  },
};
const ROBLOX_HEADER =
  '<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4"><External>null</External><External>nil</External>';

const ZERO = new THREE.Vector3();
const IDENT = new THREE.Quaternion();

// Linear easing between baked frames: Roblox interpolates exactly like the preview.
function poseItem(name, pose, children) {
  const tr = pose ? pose[name] : null;
  return item(
    'Pose',
    [
      P.cframe('CFrame', tr ? tr.p : ZERO, tr ? tr.q : IDENT),
      P.token('EasingDirection', 0),
      P.token('EasingStyle', 0), // PoseEasingStyle.Linear
      P.string('Name', name),
      P.float('Weight', 1),
    ],
    children,
  );
}

function poseTree(pose) {
  const kids = (parent) => JOINTS.filter((j) => j.parent === parent).map((j) => poseItem(j.name, pose, kids(j.name)));
  return poseItem('HumanoidRootPart', null, kids('HumanoidRootPart'));
}

export function keyframeSequenceItem(frames, data) {
  const markersByFrame = new Map();
  for (const m of data.markers) {
    if (!markersByFrame.has(m.frame)) markersByFrame.set(m.frame, []);
    markersByFrame.get(m.frame).push(m.name);
  }
  const keyframes = frames.map((f, i) => {
    const markers = (markersByFrame.get(i) || []).map((name) => item('KeyframeMarker', [P.string('Name', name), P.string('Value', '')]));
    return item('Keyframe', [P.string('Name', markers.length ? markersByFrame.get(i).join('+') : 'Keyframe'), P.float('Time', i / data.fps)], [
      poseTree(f.pose),
      ...markers,
    ]);
  });
  return item(
    'KeyframeSequence',
    [P.float('AuthoredHipHeight', data.hipHeight), P.bool('Loop', false), P.string('Name', data.name), P.token('Priority', 2)],
    keyframes,
  );
}

function luaData(data) {
  const markers = data.markers.map((m) => `\t\t${m.name} = ${num(m.time)},`).join('\n');
  const lid = [];
  for (let i = 0; i < data.lid60.length; i += 12) lid.push('\t\t' + data.lid60.slice(i, i + 12).map(num).join(', ') + ',');
  const c = data.chest;
  return `-- GENERATED by tools/build.mjs. Do not edit by hand: run \`node tools/build.mjs\`.
-- Timing data for the ChestOpenUltraRare animation (R15, Action, no loop).
-- "Animation space": origin on the ground under the HumanoidRootPart at the
-- start, -Z = the direction the character faces (towards the chest).
return {
\tAnimationName = "${data.name}",
\tDuration = ${num(data.duration)},
\tFps = ${data.fps},
\tTurnDegrees = ${data.turn}, -- final facing, to the character's left (camera side)
\tRootHeight = ${num(data.rootHeight)}, -- HumanoidRootPart centre above ground (R15 Block)
\tChest = {
\t\tWidth = ${num(c.width)},
\t\tDepth = ${num(c.depth)},
\t\tBaseHeight = ${num(c.baseHeight)},
\t\tLidHeight = ${num(c.lidHeight)},
\t\tFrontZ = ${num(c.frontZ)},
\t\tCenterZ = ${num(c.frontZ - c.depth / 2)},
\t\tHinge = Vector3.new(${c.hinge.map(num).join(', ')}),
\t},
\tMarkers = {
${markers}
\t},
\t-- Lid opening angle in degrees, sampled at 60 fps (index 1 = t 0).
\tLidFps = 60,
\tLid = {
${lid.join('\n')}
\t},
}
`;
}

export function writeRoblox(frames, data, out) {
  refCounter = 0;
  const kfsXml = keyframeSequenceItem(frames, data);
  fs.mkdirSync(out('animations'), { recursive: true });
  fs.writeFileSync(out('animations/ChestOpenUltraRare.rbxmx'), `${ROBLOX_HEADER}${kfsXml}</roblox>\n`);

  const dataLua = luaData(data);
  fs.mkdirSync(out('roblox/src'), { recursive: true });
  fs.writeFileSync(out('roblox/src/ChestOpeningData.lua'), dataLua);

  const clientPath = out('roblox/src/ChestClient.lua');
  if (!fs.existsSync(clientPath)) return;
  const clientSrc = fs.readFileSync(clientPath, 'utf8');

  // Drop-in kit: Model { Anchor, KeyframeSequence, Script(RunContext=Client) { ModuleScript } }
  refCounter = 1000;
  const anchor = item('Part', [
    P.string('Name', 'Anchor'),
    P.bool('Anchored', true),
    P.bool('CanCollide', false),
    P.bool('CanTouch', false),
    P.bool('CanQuery', false),
    P.bool('CastShadow', false),
    P.float('Transparency', 1),
    P.cframe('CFrame', new THREE.Vector3(0, 0.1, 0), IDENT),
    P.vector3('size', [data.chest.width, 0.2, data.chest.depth]),
    P.color3uint8('Color3uint8', [255, 203, 82]),
  ]);
  const module = item('ModuleScript', [P.string('Name', 'ChestOpeningData'), P.source('Source', dataLua)]);
  const script = item(
    'Script',
    [P.string('Name', 'ChestClient'), P.bool('Disabled', false), P.token('RunContext', 2), P.source('Source', clientSrc)],
    [module],
  );
  const kfsCopy = keyframeSequenceItem(frames, data);
  const animId = item('StringValue', [P.string('Name', 'AnimationId'), P.string('Value', '')]);
  const camFlag = item('BoolValue', [P.string('Name', 'CinematicCamera'), P.bool('Value', true)]);
  const model = item('Model', [P.string('Name', 'UltraRareChest'), P.token('LevelOfDetail', 0)], [anchor, kfsCopy, animId, camFlag, script]);
  fs.writeFileSync(out('roblox/UltraRareChestKit.rbxmx'), `${ROBLOX_HEADER}${model}</roblox>\n`);
}
